import frappe
from frappe import _
from frappe.model.document import Document


class MaintenanceOccurrence(Document):
	def before_insert(self):
		if not self.flags.fsm_occurrence_command:
			frappe.throw(
				_("Maintenance Occurrences can only be generated by the PM engine."), frappe.PermissionError
			)

	def validate(self):
		before = self.get_doc_before_save()
		if before and before.status != self.status and not self.flags.fsm_occurrence_command:
			frappe.throw(_("Occurrence status can only change through a PM command."), frappe.PermissionError)
		if (
			self.released_job
			and frappe.db.get_value("Service Job", self.released_job, "customer") != self.customer
		):
			frappe.throw(_("Released Job must belong to the Occurrence Customer."), frappe.ValidationError)

	def on_trash(self):
		frappe.throw(
			_("Maintenance Occurrences are durable scheduling evidence and cannot be deleted."),
			frappe.PermissionError,
		)
